// Generates the native app's theme (android-native/app/.../ui/theme/ThemeTokens.kt) from the Expo app's tokens
// (src/ui-android/theme: colors, typography, spacing), and copies the bundled fonts (Baloo 2, Lexend; SIL OFL 1.1) to
// res/font. One source until the cutover.
//   node scripts/export-native-theme.mjs          # write
//   node scripts/export-native-theme.mjs --check  # exit 1 if out of date
import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { registerHooks } from "node:module";
import ts from "typescript";

registerHooks({
  resolve(specifier, context, next) {
    if (specifier === "react-native") {
      const src = `export const Platform = { OS: "android", select: (o) => o.android ?? o.default };`;
      return { url: `data:text/javascript,${encodeURIComponent(src)}`, shortCircuit: true };
    }
    try {
      return next(specifier, context);
    } catch (e) {
      if (specifier.startsWith(".") && !/\.[cm]?[jt]sx?$|\.json$/.test(specifier)) return next(`${specifier}.ts`, context);
      throw e;
    }
  },
  // Type-only imports without "type" (ThemeId, FontScale from settings.ts, which needs Expo) must be dropped.
  load(url, context, next) {
    if (!url.startsWith("file:") || !url.endsWith(".ts")) return next(url, context);
    const source = readFileSync(fileURLToPath(url), "utf8");
    const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
    return { format: "module", source: js, shortCircuit: true };
  },
});

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const app = join(root, "android-native/app/src/main");
const themeDir = join(root, "src/ui-android/theme");
const colors = await import(join(themeDir, "colors.ts"));
const typo = await import(join(themeDir, "typography.ts"));
const space = await import(join(themeDir, "spacing.ts"));

const camel = (path) => path.map((p, i) => (/^\d/.test(p) || i === 0 ? p : p[0].toUpperCase() + p.slice(1))).join("");
function color(v) {
  let m = /^#([0-9a-f]{6})$/i.exec(v);
  if (m) return `Color(0xFF${m[1].toUpperCase()})`;
  m = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/i.exec(v);
  if (m) {
    const a = Math.round(Number(m[4]) * 255);
    const hex = (n) => Number(n).toString(16).padStart(2, "0").toUpperCase();
    return `Color(0x${hex(a)}${hex(m[1])}${hex(m[2])}${hex(m[3])})`;
  }
  throw new Error(`unknown color ${v}`);
}
function flatten(obj, path = [], out = []) {
  for (const [k, v] of Object.entries(obj)) {
    if (typeof v === "object" && v) flatten(v, [...path, k], out);
    else if (typeof v === "string" && /^(#|rgba)/.test(v)) out.push([camel([...path, k]), color(v)]);
  }
  return out;
}
const themes = colors.THEMES;
const fields = flatten(themes[0]);
for (const t of themes) {
  const f = flatten(t).map(([k]) => k).join(",");
  if (f !== fields.map(([k]) => k).join(",")) throw new Error(`theme ${t.id} has different tokens`);
}
const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$");

let kt = `// Generated by scripts/export-native-theme.mjs from src/ui-android/theme. Do not edit by hand.
package team.sopa.boar.ui.theme

import androidx.compose.ui.graphics.Color

/** One theme's color tokens (src/ui-android/theme/colors.ts), named by their path: bg.card -> bgCard, emerald[500] -> emerald500. */
data class BoarColors(
    val id: String,
    val name: String,
    val icon: String,
${fields.map(([k]) => `    val ${k}: Color,`).join("\n")}
)

object ThemeTokens {
${themes.map((t) => `    val ${t.id} = BoarColors(
        id = "${esc(t.id)}", name = "${esc(t.name)}", icon = "${esc(t.icon)}",
${flatten(t).map(([k, v]) => `        ${k} = ${v},`).join("\n")}
    )`).join("\n\n")}

    val all = listOf(${themes.map((t) => t.id).join(", ")})
    const val DEFAULT_ID = "${esc(themes[0].id)}"
    fun byId(id: String?) = all.firstOrNull { it.id == id } ?: ${themes[0].id}
}

/** spacing.ts */
object Spacing {
${Object.entries(space.spacing).map(([k, v]) => `    const val ${k} = ${v}`).join("\n")}
}

/** spacing.ts radii */
object Radii {
${Object.entries(space.radii).map(([k, v]) => `    const val ${k} = ${v}`).join("\n")}
}

/** typography.ts: size, line height and weight per text style, per text-size setting (font family resolved in Type.kt). */
data class TextSpec(val family: String, val size: Float, val lineHeight: Float?, val weight: Int, val letterSpacing: Float?)

object TypeTokens {
    val scales = listOf(${typo.FONT_SCALES.map((s) => `"${esc(typeof s === "string" ? s : s.id)}"`).join(", ")})
${typo.FONT_SCALES.map((s) => {
  const id = typeof s === "string" ? s : s.id;
  const t = typo.getTypography(id);
  // Grouped as mono.* and ui.*: keys "mono.sm", "ui.body".
  const entries = Object.entries(t).flatMap(([g, group]) => Object.entries(group).map(([k, v]) => [`${g}.${k}`, v]));
  return `    val ${id.replace(/-(\w)/g, (_, c) => c.toUpperCase())} = mapOf(
${entries.map(([k, v]) => `        "${k}" to TextSpec("${esc(v.fontFamily ?? "")}", ${v.fontSize}f, ${v.lineHeight != null ? `${v.lineHeight}f` : "null"}, ${Number(v.fontWeight ?? 400)}, ${v.letterSpacing != null ? `${v.letterSpacing}f` : "null"}),`).join("\n")}
    )`;
}).join("\n")}
}
`;

const ktPath = join(app, "java/team/sopa/boar/ui/theme/ThemeTokens.kt");
const fonts = {
  "baloo2_700bold.ttf": "@expo-google-fonts/baloo-2/700Bold/Baloo2_700Bold.ttf",
  "baloo2_800extrabold.ttf": "@expo-google-fonts/baloo-2/800ExtraBold/Baloo2_800ExtraBold.ttf",
  "lexend_400regular.ttf": "@expo-google-fonts/lexend/400Regular/Lexend_400Regular.ttf",
  "lexend_500medium.ttf": "@expo-google-fonts/lexend/500Medium/Lexend_500Medium.ttf",
  "lexend_600semibold.ttf": "@expo-google-fonts/lexend/600SemiBold/Lexend_600SemiBold.ttf",
  "lexend_700bold.ttf": "@expo-google-fonts/lexend/700Bold/Lexend_700Bold.ttf",
};
const images = ["mascot.png", "boar.png"];
if (process.argv.includes("--check")) {
  const stale = !existsSync(ktPath) || readFileSync(ktPath, "utf8") !== kt || Object.keys(fonts).some((f) => !existsSync(join(app, "res/font", f))) || images.some((f) => !existsSync(join(app, "res/drawable-nodpi", f)));
  if (stale) { console.error("theme out of date: run node scripts/export-native-theme.mjs"); process.exit(1); }
  process.exit(0);
}
mkdirSync(dirname(ktPath), { recursive: true });
writeFileSync(ktPath, kt);
mkdirSync(join(app, "res/font"), { recursive: true });
for (const [name, src] of Object.entries(fonts)) copyFileSync(join(root, "node_modules", src), join(app, "res/font", name));
// The mascot images the Expo screens show (assets/mascot.png in the header, empty chat and answers; boar.png in theme previews).
mkdirSync(join(app, "res/drawable-nodpi"), { recursive: true });
for (const img of images) copyFileSync(join(root, "assets", img), join(app, "res/drawable-nodpi", img));
console.log(`wrote ${ktPath} (${themes.length} themes, ${fields.length} color tokens) and ${Object.keys(fonts).length} fonts`);
